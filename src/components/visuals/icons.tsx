/** `box` positions the icon inside a parent SVG (x, y, size). */
export function VisualIcon({ name, className, box }: { name?: string; className?: string; box?: { x: number; y: number; size: number } }) {
  const Icon = (name && VISUAL_ICONS[name]) || Dot;
  return <Icon className={className} aria-hidden {...(box ? { x: box.x, y: box.y, width: box.size, height: box.size } : {})} />;
}
