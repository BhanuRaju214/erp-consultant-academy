/**
 * Visual asset pipeline check.  Run: npm run visuals:check
 *
 * 1. Every visual block in every lesson is valid JSON for its schema.
 * 2. Every registered asset file exists, has alt text, and respects size budgets.
 * 3. Every visual-figure block points to a registered asset; no orphan files.
 * 4. Writes docs/visual-learning/asset-register.md (all visuals per lesson).
 * Exits with code 1 when any error is found.
 */
import fs from "node:fs";
import path from "node:path";
import { allCourses } from "../src/content";
import { visualAssets } from "../src/content/visuals/registry";
import { extractVisualBlocks, parseVisual } from "../src/lib/visuals/schemas";

const ROOT = process.cwd();
const PUBLIC = path.join(ROOT, "public");
const LIMITS: Record<string, number> = { svg: 400_000, png: 300_000, webp: 200_000, jpg: 200_000 };
const errors: string[] = [];
const warnings: string[] = [];

// ---- 1. blocks -------------------------------------------------------------------
type Row = { course: string; lesson: string; title: string; blocks: { type: string; title: string }[] };
const rows: Row[] = [];
const figureSrcs = new Set<string>();
for (const c of allCourses) {
  for (const m of c.modules) {
    for (const l of m.lessons) {
      const blocks: Row["blocks"] = [];
      for (const b of extractVisualBlocks(l.body)) {
        const r = parseVisual(b.type, b.source);
        if (!r.ok) {
          errors.push(`${c.slug}/${l.slug}: visual-${b.type}: ${r.error}`);
          continue;
        }
        const d = r.data as { title?: string; src?: string; question?: string; company?: string };
        if (b.type === "figure" && d.src) figureSrcs.add(d.src);
        blocks.push({ type: b.type, title: d.title ?? d.question ?? d.company ?? (d.src ? path.basename(d.src) : "") });
      }
      rows.push({ course: c.slug, lesson: l.slug, title: l.title, blocks });
    }
  }
}

// ---- 2. registered files ------------------------------------------------------------
const registered = new Set<string>();
for (const a of visualAssets) {
  registered.add(a.src);
  const file = path.join(PUBLIC, a.src);
  if (!a.src.startsWith("/visuals/")) errors.push(`${a.src}: must live under /visuals/`);
  if (!fs.existsSync(file)) {
    errors.push(`${a.src}: file not found in public/`);
    continue;
  }
  const size = fs.statSync(file).size;
  if (size > (LIMITS[a.format] ?? 300_000)) errors.push(`${a.src}: ${Math.round(size / 1024)} KB exceeds the ${a.format} budget of ${Math.round(LIMITS[a.format] / 1024)} KB`);
  if (a.alt.trim().length < 20) errors.push(`${a.src}: alt text too short — describe what the visual shows`);
  if (!a.rights.trim()) errors.push(`${a.src}: usage rights / attribution missing`);
  if (a.width > 1600) warnings.push(`${a.src}: width ${a.width}px — 1600px is enough for retina screens`);
  if (!/^[a-z0-9/_.-]+$/.test(a.src)) errors.push(`${a.src}: use lowercase kebab-case file names`);
  if (a.source === "odoo-screenshot" && !a.capturedFrom) errors.push(`${a.src}: screenshots must record capturedFrom (Odoo version + training database)`);
}

// ---- 3. cross-checks ---------------------------------------------------------------
for (const src of figureSrcs) if (!registered.has(src)) errors.push(`visual-figure uses unregistered asset ${src} — add it to src/content/visuals/registry.ts`);
const visualsDir = path.join(PUBLIC, "visuals");
if (fs.existsSync(visualsDir)) {
  const walk = (d: string): string[] => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]));
  for (const f of walk(visualsDir)) {
    if (/README|\.gitkeep$/i.test(f)) continue;
    const src = "/" + path.relative(PUBLIC, f).split(path.sep).join("/");
    if (!registered.has(src)) warnings.push(`${src}: file is not registered (orphan)`);
  }
}

// ---- 4. asset register ---------------------------------------------------------------
const byType = new Map<string, number>();
for (const r of rows) for (const b of r.blocks) byType.set(b.type, (byType.get(b.type) ?? 0) + 1);
const visualLessons = rows.filter((r) => r.blocks.length);
const lines = [
  "# Visual asset register",
  "",
  "_Generated by `npm run visuals:check` — do not edit by hand._",
  "",
  `- Lessons with authored visual blocks: **${visualLessons.length} / ${rows.length}**`,
  `- Authored visual blocks: **${[...byType.values()].reduce((a, b) => a + b, 0)}** (${[...byType.entries()].map(([t, n]) => `${t} ${n}`).join(", ") || "none"})`,
  `- Registered file assets: **${visualAssets.length}**`,
  "- Automatic enhancements (all lessons): Key takeaways → summary cards, `A → B → C` lines → flow chips, tips/warnings → callouts, ASCII diagrams → framed diagrams, task lists → practice checklists.",
  "",
  "## In-portal visual blocks (source: in-house components, no external rights)",
  "",
  "| Course | Lesson | # | Block type | Title / concept |",
  "|---|---|---|---|---|",
  ...visualLessons.flatMap((r) => r.blocks.map((b, i) => `| ${r.course} | ${r.lesson} | ${i + 1} | ${b.type} | ${b.title.replace(/\|/g, "/")} |`)),
  "",
  "## File assets",
  "",
  "| File | Course / lesson | Concept | Type | Source | Format | Size (px) | Caption | Alt text | Rights |",
  "|---|---|---|---|---|---|---|---|---|---|",
  ...visualAssets.map((a) => `| ${a.src} | ${a.course} / ${a.lesson} | ${a.concept} | ${a.type} | ${a.source}${a.promptId ? ` (${a.promptId})` : ""} | ${a.format} | ${a.width}×${a.height} | ${a.caption} | ${a.alt} | ${a.rights} |`),
  ...(visualAssets.length ? [] : ["| — | — | — | — | — | — | — | — | — | No file assets registered yet (Napkin exports and screenshots pending) |"]),
  "",
];
fs.mkdirSync(path.join(ROOT, "docs", "visual-learning"), { recursive: true });
fs.writeFileSync(path.join(ROOT, "docs", "visual-learning", "asset-register.md"), lines.join("\n"));

console.log(`Lessons with visual blocks: ${visualLessons.length}/${rows.length} · blocks: ${[...byType.values()].reduce((a, b) => a + b, 0)} · file assets: ${visualAssets.length}`);
for (const w of warnings) console.log("WARN ", w);
for (const e of errors) console.log("ERROR", e);
console.log(errors.length ? `✗ ${errors.length} error(s)` : "✓ visuals OK — docs/visual-learning/asset-register.md updated");
process.exit(errors.length ? 1 : 0);
